const originals = new Map();
document.querySelectorAll("[data-i18n], [data-i18n-html]").forEach((element) => {
  originals.set(element, element.hasAttribute("data-i18n-html") ? element.innerHTML : element.textContent);
});
document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => originals.set(element, element.placeholder));

const params = new URLSearchParams(window.location.search);
const storedLanguage = localStorage.getItem("tif-language");
let language = params.get("lang") || storedLanguage || (navigator.language.toLowerCase().startsWith("es") ? "es" : "en");
if (!['en', 'es'].includes(language)) language = 'en';

const setLanguage = (nextLanguage) => {
  language = nextLanguage;
  document.documentElement.lang = language;
  document.documentElement.dataset.lang = language;
  localStorage.setItem("tif-language", language);

  document.querySelectorAll("[data-i18n], [data-i18n-html]").forEach((element) => {
    const key = element.dataset.i18n || element.dataset.i18nHtml;
    const value = language === "es" ? es[key] : originals.get(element);
    if (!value) return;
    if (element.hasAttribute("data-i18n-html")) element.innerHTML = value;
    else element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = language === "es" ? es[element.dataset.i18nPlaceholder] : originals.get(element);
  });

  const langToggle = document.querySelector("[data-lang-toggle]");
  langToggle?.setAttribute("aria-label", language === "es" ? "Switch to English" : "Cambiar a español");
  document.title = language === "es"
    ? "Tulum Innovation Fest 2026 | Partnerships estratégicos"
    : "Tulum Innovation Fest 2026 | Strategic Partnerships";
  document.querySelector('meta[name="description"]')?.setAttribute("content", language === "es"
    ? "Conviértete en partner de Tulum Innovation Fest 2026. Una plataforma medible que conecta innovación, capital, founders, hospitalidad y cultura en Tulum."
    : "Partner with Tulum Innovation Fest 2026. Build a measurable platform across innovation, capital, founders, hospitality and culture in Tulum.");
};

setLanguage(language);

document.querySelector("[data-lang-toggle]")?.addEventListener("click", () => {
  setLanguage(language === "en" ? "es" : "en");
});

const header = document.querySelector("[data-header]");
const nav = document.querySelector("[data-nav]");
const navToggle = document.querySelector("[data-nav-toggle]");

const closeNavigation = () => {
  nav?.classList.remove("is-open");
  navToggle?.setAttribute("aria-expanded", "false");
  document.body.classList.remove("nav-open");
};

navToggle?.addEventListener("click", () => {
  const isOpen = nav?.classList.toggle("is-open");
  navToggle.setAttribute("aria-expanded", String(Boolean(isOpen)));
  document.body.classList.toggle("nav-open", Boolean(isOpen));
});

nav?.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeNavigation));
document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeNavigation();
});

const updateHeader = () => header?.classList.toggle("is-scrolled", window.scrollY > 24);
updateHeader();
window.addEventListener("scroll", updateHeader, { passive: true });

const packageSelect = document.querySelector("[data-package-select]");
document.querySelectorAll("[data-open-form]").forEach((button) => {
  button.addEventListener("click", () => {
    const selectedPackage = button.dataset.package;
    if (selectedPackage && packageSelect) packageSelect.value = selectedPackage;
    closeNavigation();
    document.querySelector("#contact")?.scrollIntoView({ behavior: "smooth", block: "start" });
    window.setTimeout(() => document.querySelector('[name="name"]')?.focus({ preventScroll: true }), 650);
  });
});

const revealElements = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.08, rootMargin: "0px 0px -5%" });
  revealElements.forEach((element) => observer.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}

const form = document.querySelector("[data-partner-form]");
const formStatus = document.querySelector("[data-form-status]");
form?.addEventListener("submit", (event) => {
  event.preventDefault();
  if (!form.reportValidity()) return;

  const data = new FormData(form);
  const subject = `[TIF 2026 Partnership] ${data.get("company")} — ${data.get("package")}`;
  const body = [
    `Name: ${data.get("name")}`,
    `Role: ${data.get("role")}`,
    `Company: ${data.get("company")}`,
    `Email: ${data.get("email")}`,
    `Partnership interest: ${data.get("package")}`,
    `Investment range: ${data.get("budget")}`,
    `Business objective: ${data.get("objective")}`,
    "",
    "Context and desired outcome:",
    data.get("notes")
  ].join("\n");

  if (formStatus) {
    formStatus.textContent = language === "es"
      ? "Abriendo tu aplicación de correo con el brief preparado…"
      : "Opening your email app with the prepared brief…";
  }
  window.location.href = `mailto:innovation@likegroup.io?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
});
